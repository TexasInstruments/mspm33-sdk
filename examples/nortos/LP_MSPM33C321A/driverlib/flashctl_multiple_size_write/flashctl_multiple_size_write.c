#include "ti_msp_dl_config.h"

/* Address in main memory to write to */
#define MAIN_BASE_ADDRESS (0x00003000)

/* 8-bit data to write to flash */
uint8_t gData8 = 0x11;

/* 16-bit data to write to flash */
uint16_t gData16 = 0x2222;

/* 32-bit data to write to flash */
uint32_t gData32 = 0x33333333;

/* Array to write 64-bits to flash */
uint32_t gDataArray64[] = {0xABCDEF00, 0x12345678};

/* Array to write 96-bits to flash */
uint32_t gDataArray96[] = {0xABCDEF00, 0x12345678, 0x98765432};

/* Array to write 128-bits to flash */
uint32_t gDataArray128[] = {0xABCDEF00, 0x12345678, 0x98765432, 0x12345678};

/*
 * Array to write multiple 64-bit data words to flash. Data must be loaded
 * 32-bits at a time, but a single word program is executed.
 */
uint32_t gDataArray64MultipleWords[] = {0xCAFEBABE, 0xDEADBEEF, 0xCAFEBABE,
    0xDEADBEEF, 0xCAFEBABE, 0xDEADBEEF, 0xCAFEBABE, 0xDEADBEEF, 0xCAFEBABE,
    0xDEADBEEF};

volatile DL_FLASHCTL_COMMAND_STATUS gCmdStatus;

#ifdef __SLATE_INTERNAL__
#define TEST_MEM_ERASED 1
#define TEST_COMPLETE 2
volatile uint8_t gTestFlow = 0;

#endif

/* Codes to understand where error occured */
#define NO_ERROR 0
#define ERROR_ERASE 1
#define ERROR_8BIT_W 2
#define ERROR_16BIT_W 3
#define ERROR_32BIT_W 4
#define ERROR_64BIT_W 5
#define ERROR_96BIT_W 6
#define ERROR_128BIT_W 7
#define ERROR_64BIT_W_BLOCKING 8
#define ERROR_SET_WAIT_STATE 9

volatile uint8_t gErrorType = NO_ERROR;

int main(void)
{
    SYSCFG_DL_init();

    DL_GSC_acquireFlashSemaphore(GSC);

    DL_FlashCTL_executeClearStatus(FLASHCTL);

    /* Unprotect sector in main memory with ECC generated by hardware */
    DL_FlashCTL_unprotectSector(
        FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
    /* Erase sector in main memory */
    gCmdStatus = DL_FlashCTL_eraseMemoryFromRAM(
        FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_COMMAND_SIZE_SECTOR);
    if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
        /* If command was not successful, set error flag */
        gErrorType = ERROR_ERASE;
    }

    if (gErrorType == NO_ERROR) {
        /* 8-bit write to flash in main memory */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM8WithECCGenerated(
            FLASHCTL, MAIN_BASE_ADDRESS, &gData8);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_8BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
         * 16-bit write to flash in main memory with ECC generated by hardware.
         * The target program address must be a flash word address
         * (8-byte aligned), so we increase the address in increments of 8.
         */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM16WithECCGenerated(
            FLASHCTL, (MAIN_BASE_ADDRESS + 16), &gData16);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_16BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /* 32-bit write to flash in main memory with ECC generated by hardware */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM32WithECCGenerated(
            FLASHCTL, (MAIN_BASE_ADDRESS + 32), &gData32);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_32BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
        * 64-bit write to flash in main memory with ECC generated by hardware.
        * Data must be loaded 32-bits at a time, but a single word program
        * is executed
        */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM64WithECCGenerated(
            FLASHCTL, (MAIN_BASE_ADDRESS + 48), &gDataArray64[0]);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_64BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
        * 96-bit write to flash in main memory with ECC generated by hardware.
        * Data must be loaded 32-bits at a time, but a single word program
        * is executed
        */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM96WithECCGenerated(
            FLASHCTL, (MAIN_BASE_ADDRESS + 64), &gDataArray96[0]);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_96BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
        * 128-bit write to flash in main memory with ECC generated by hardware.
        * Data must be loaded 32-bits at a time, but a single word program
        * is executed
        */
        DL_FlashCTL_unprotectSector(
            FLASHCTL, MAIN_BASE_ADDRESS, DL_FLASHCTL_REGION_SELECT_MAIN);
        gCmdStatus = DL_FlashCTL_programMemoryFromRAM128WithECCGenerated(
            FLASHCTL, (MAIN_BASE_ADDRESS + 80), &gDataArray128[0]);
        if (gCmdStatus == DL_FLASHCTL_COMMAND_STATUS_FAILED) {
            /* If command was not successful, set error flag */
            gErrorType = ERROR_128BIT_W;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
        * Write five, 64-bit flash words, but one flash word is programmed at a
        * time. The flash controller hardware will handle generating the 8-bit
        * ECC code for each flash word.
        */
        gCmdStatus =
            DL_FlashCTL_programMemoryBlockingFromRAM64WithECCGenerated(
                FLASHCTL, (MAIN_BASE_ADDRESS + 96),
                &gDataArray64MultipleWords[0],
                sizeof(gDataArray64MultipleWords) / sizeof(uint32_t),
                DL_FLASHCTL_REGION_SELECT_MAIN);
        if (gCmdStatus != DL_FLASHCTL_COMMAND_STATUS_PASSED) {
            /* If command did not pass, set error flag */
            gErrorType = ERROR_64BIT_W_BLOCKING;
        }
    }

    if (gErrorType == NO_ERROR) {
        /*
        * Write five, 64-bit flash words, but one flash word is programmed at a
        * time. The flash controller hardware will handle generating the 8-bit
        * ECC code for each flash word.
        */
        DL_FlashCTL_setWaitState(FLASHCTL, 5);
        if (DL_FlashCTL_waitForCmdDone(FLASHCTL) == 0) {
            gCmdStatus = DL_FLASHCTL_COMMAND_STATUS_FAILED;
        } else {
            gCmdStatus = DL_FLASHCTL_COMMAND_STATUS_PASSED;
        }
        if (gCmdStatus != DL_FLASHCTL_COMMAND_STATUS_PASSED) {
            /* If command did not pass, set error flag */
            gErrorType = ERROR_SET_WAIT_STATE;
        }
    }

    DL_GSC_clearFlashSemaphore(GSC);

    /* After successful completion, set PASS LED */
    if (gErrorType == NO_ERROR) {
        DL_GPIO_setPins(GPIO_LEDS_PORT,
            GPIO_LEDS_PASS_LED_PIN);
        delay_cycles(1000);
    }
    /* Unsuccessful example run, set FAIL LED */
    else {
        DL_GPIO_setPins(GPIO_LEDS_PORT,
            GPIO_LEDS_FAIL_LED_PIN);
        delay_cycles(1000);
        /* Check gErrorType value */
    }
    __BKPT(0);
}
