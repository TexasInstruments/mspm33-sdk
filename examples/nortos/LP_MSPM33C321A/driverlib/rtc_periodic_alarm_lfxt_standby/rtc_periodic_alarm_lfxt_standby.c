#include "ti_msp_dl_config.h"
void RTC_INST_IRQHandler(void)
{
    switch (DL_RTC_getPendingInterrupt(RTC)) {
        case DL_RTC_IIDX_PRESCALER1:
            /* Toggle LED */
            DL_GPIO_togglePins(GPIO_LEDS_PORT, GPIO_LEDS_PASS_LED_PIN);
        default:
            break;
    }
}
int main(void)
{
    /* Enable the RTC interrupt at NVIC */
    NVIC_EnableIRQ(RTC_INST_INT_IRQN);
    SYSCFG_DL_init();
    /* Start RTC clock */
    DL_RTC_enableClockControl(RTC);
    while (1) {
        __WFI();
    }
    return 0;
}
