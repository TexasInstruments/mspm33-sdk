#include "ti_msp_dl_config.h"
void NMI_Handler(void)
{
    switch (DL_SYSCTL_getPendingNonMaskableInterrupt()) {
        case DL_SYSCTL_NMI_IIDX_SECURITY:        
                if (DL_EAM_getSecurityErrorFlag(EAM) ==
                    DL_EAM_SECURITY_ERROR_FPI_ILLADDR) {
                    DL_GPIO_setPins(GPIO_LEDS_PORT, GPIO_LEDS_PASS_LED_PIN);
                }
                DL_EAM_clearSecurityErrorFlag(EAM);       
            break;
        default:
            break;
    }
}
int main(void)
{
    NVIC_EnableIRQ(NonMaskableInt_IRQn);
    SYSCFG_DL_init();
    DL_GSC_acquireFlashSemaphore(GSC);

    /* Unprotect sector in main memory with ECC generated by hardware */
    DL_FlashCTL_unprotectSector(
        FLASHCTL, 0x00000000, DL_FLASHCTL_REGION_SELECT_MAIN);
    /* Erase sector in main memory */
    DL_FlashCTL_eraseMemoryFromRAM(
        FLASHCTL, 0x30000000, DL_FLASHCTL_COMMAND_SIZE_SECTOR);
    __BKPT(0);
    return 0;
}
