/* SRAM buffer to store the SHA3-384 OID in DER format */
static const uint8_t sha3_384_oid_der[11] = {
    0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x09
};

/* SRAM buffer to store the SHA3-384 message digest (48 bytes / 12 words) */
static uint32_t md[12];

/* SRAM buffer to store the pre-hash message (OID || md) (11 + 48 bytes) */
static uint8_t prehash_msg[sizeof(sha3_384_oid_der) + sizeof(md)];

int main(void)
{
    crypto_hash_stat_t hashStat;
    crypto_mldsa_stat_t stat;
    uint32_t i;
    uint8_t *p_md;

    SYSCFG_DL_init();

    /* Compute the message SHA3-384 hash digest */
    hashStat = Crypto_SHA3_384(cavp_mldsa_44_verify_id16_msg, 
                               sizeof(cavp_mldsa_44_verify_id16_msg), 
                               md);

    /* If the operation was not successful, jump to error trap */
    if (hashStat != CRYPTO_HASH_STAT_OK) {
        goto err;
    }

    /* Assemble the OID || MD pre-hash message for pre-hash verification */
    for (i=0; i<sizeof(sha3_384_oid_der); i++) {
        prehash_msg[i] = sha3_384_oid_der[i];
    }
    p_md = (uint8_t*)&md[0];
    for (i=sizeof(sha3_384_oid_der); i<sizeof(prehash_msg); i++) {
        prehash_msg[i] = *(p_md++);
    }

    /* Run the verify operation */
    stat = Crypto_MLDSA_44_verify(
        cavp_mldsa_44_verify_id16_sig, sizeof(cavp_mldsa_44_verify_id16_sig),
        prehash_msg, sizeof(prehash_msg),
        cavp_mldsa_44_verify_id16_ctx, sizeof(cavp_mldsa_44_verify_id16_ctx),
        cavp_mldsa_44_verify_id16_pk,
        CRYPTO_MLDSA_SIG_MODE_PREHASH);

    /* If the operation was not successful, jump to error trap */
    if (stat != CRYPTO_MLDSA_STAT_VALID_SIGNATURE) {
        goto err;
    }

    /* Trap here on a pass condition */
    while (1) { 
        __NOP(); 
    }

err:
    /* Trap here on an error condition */
    while (1) { 
        __NOP(); 
    }
}
