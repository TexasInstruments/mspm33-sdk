/* SRAM buffer to store the SHA-256 OID in DER format */
static const uint8_t sha256_oid_der[11] = {
    0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01
};

/* SRAM buffer to store the SHA-256 message digest (32 bytes / 8 words) */
static uint32_t md[8];

/* SRAM buffer to store the pre-hash message (OID || md) (11 + 32 bytes) */
static uint8_t prehash_msg[sizeof(sha256_oid_der) + sizeof(md)];

int main(void)
{
    crypto_hash_stat_t hashStat;
    crypto_mldsa_stat_t stat;
    uint32_t i;
    uint8_t *p_md;

    SYSCFG_DL_init();

    /* Compute the message SHA-256 hash digest */
    hashStat = Crypto_SHA256(cavp_mldsa_87_verify_id81_msg, 
                             sizeof(cavp_mldsa_87_verify_id81_msg), 
                             md);

    /* If the operation was not successful, jump to error trap */
    if (hashStat != CRYPTO_HASH_STAT_OK) {
        goto err;
    }

    /* Assemble the OID || MD pre-hash message for pre-hash verification */
    for (i=0; i<sizeof(sha256_oid_der); i++) {
        prehash_msg[i] = sha256_oid_der[i];
    }
    p_md = (uint8_t*)&md[0];
    for (i=sizeof(sha256_oid_der); i<sizeof(prehash_msg); i++) {
        prehash_msg[i] = *(p_md++);
    }

    /* Run the verify operation */
    stat = Crypto_MLDSA_87_verify(
        cavp_mldsa_87_verify_id81_sig, sizeof(cavp_mldsa_87_verify_id81_sig),
        prehash_msg, sizeof(prehash_msg),
        cavp_mldsa_87_verify_id81_ctx, sizeof(cavp_mldsa_87_verify_id81_ctx),
        cavp_mldsa_87_verify_id81_pk,
        CRYPTO_MLDSA_SIG_MODE_PREHASH);

    /* If the operation was not successful, jump to error trap */
    if (stat != CRYPTO_MLDSA_STAT_VALID_SIGNATURE) {
        goto err;
    }

    /* Trap here on a pass condition */
    while (1) { 
        __NOP(); 
    }

err:
    /* Trap here on an error condition */
    while (1) { 
        __NOP(); 
    }
}
