/*!****************************************************************************
 *  @file       ec_ecdsa_p521_verify.c
 *  @brief      Elliptic curve module ECDSA P-521 verify basic example
 * 
 *  This code example demonstrates how to use the ECDSA verify function
 *  over the NIST curve P-521 to verify a signature.
 *
 *  This example focuses on the ECDSA operation, and excludes any pre hashing.
 *
 ******************************************************************************
 */

#include "ti_msp_dl_config.h"
#include "ti/crypto/include/msp-crypto-lib.h"

/* ECDSA P-521 operates on 68-byte parameters */
#define P521_UNIT_LEN (68U)

/* The NIST CAVP ECDSA sign message digest (MD) vector to sign*/
static const uint8_t cavp_ecdsa_verify_p521_md[P521_UNIT_LEN] = {
    0x0, 0x0, 0x0, 0x0, 0x65, 0xf8, 0x34, 0x8, 0x9, 0x22, 0x61, 0xbd, 
    0xa5, 0x99, 0x38, 0x9d, 0xf0, 0x33, 0x82, 0xc5, 0xbe, 0x1, 0xa8, 0x1f, 
    0xe0, 0xa, 0x36, 0xf3, 0xf4, 0xbb, 0x65, 0x41, 0x26, 0x3f, 0x80, 0x16, 
    0x27, 0xc4, 0x40, 0xe5, 0x8, 0x9, 0x71, 0x2b, 0xc, 0xac, 0xe7, 0xc2, 
    0x17, 0xe6, 0xe5, 0x5, 0x1a, 0xf8, 0x1d, 0xe9, 0xbf, 0xec, 0x32, 0x4, 
    0xdc, 0xd6, 0x3c, 0x4f, 0x9a, 0x74, 0x10, 0x47
};

