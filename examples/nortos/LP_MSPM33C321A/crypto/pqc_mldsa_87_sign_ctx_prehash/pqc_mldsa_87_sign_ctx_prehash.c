/* The SHA-512 OID in DER format */
static const uint8_t oid[11] = {
    0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x03
};

/* SRAM buffer to store the SHA-512 message digest (64 bytes / 16 words) */
static uint32_t md[16];

/* SRAM buffer to store the pre-hash message (OID || md) (11 + 64 bytes) */
static uint8_t prehash_msg[sizeof(oid) + sizeof(md)];

/* SRAM buffer to store actual computed signature value */
static uint8_t sig_act[CRYPTO_MLDSA_87_SIG_LEN];

int main(void)
{
    crypto_hash_stat_t hashStat;
    crypto_mldsa_stat_t sigStat;
    uint32_t sigLen;
    uint32_t i;
    uint8_t *p_md;

    SYSCFG_DL_init();

    /* Compute the message SHA-512 hash digest */
    hashStat = Crypto_SHA512(cavp_mldsa_87_sign_id81_msg, 
                  sizeof(cavp_mldsa_87_sign_id81_msg), 
                  md);
    /* If the operation was not successful, jump to error trap */
    if (hashStat != CRYPTO_HASH_STAT_OK) {
        goto err;
    }

    /* Assemble the OID || MD pre-hash message for pre-hash signing */
    for (i=0; i<sizeof(oid); i++) {
        prehash_msg[i] = oid[i];
    }
    p_md = (uint8_t*)&md[0];
    for (i=sizeof(oid); i<sizeof(prehash_msg); i++) {
        prehash_msg[i] = *(p_md++);
    }

    /* Compute the signature */
    sigStat = Crypto_MLDSA_87_sign(
        sig_act, &sigLen,
        prehash_msg, sizeof(prehash_msg),
        cavp_mldsa_87_sign_id81_ctx, sizeof(cavp_mldsa_87_sign_id81_ctx),
        NULL, 0,
        cavp_mldsa_87_sign_id81_sk,
        CRYPTO_MLDSA_SIG_MODE_PREHASH);

    /* If the operation was not successful, jump to error trap */
    if (sigStat != CRYPTO_MLDSA_STAT_OK) {
        goto err;
    }

    /* If the signature length is incorrect, jump to error trap */
    if (sigLen != CRYPTO_MLDSA_87_SIG_LEN) {
        goto err;
    }

    /* Check generated signature against CAVP expected signature */
    for (i=0; i<CRYPTO_MLDSA_87_SIG_LEN; i++) {
        if (sig_act[i] != cavp_mldsa_87_sign_id81_sig_exp[i]) {
            goto err;
        }
    }

    /* Trap here on a pass condition */
    while (1) { 
        __NOP(); 
    }

err:
    /* Trap here on an error condition */
    while (1) { 
        __NOP(); 
    }
}
