/*!****************************************************************************
 *  @file       ec_ecdsa_p521_sign.c
 *  @brief      Elliptic curve module ECDSA P-521 sign basic example
 * 
 *  This code example demonstrates how to use the ECDSA sign function
 *  over the NIST curve P-521 to generate a signature.
 *
 *  This example focuses on the ECDSA operation, and excludes any pre hashing.
 *
 ******************************************************************************
 */

#include "ti_msp_dl_config.h"
#include "ti/crypto/include/msp-crypto-lib.h"

/* ECDSA P-384 operates on 68-byte parameters */
#define P521_UNIT_LEN (68U)

/* The NIST CAVP ECDSA sign message digest (MD) vector to sign*/
static const uint8_t cavp_ecdsa_sign_p521_md[P521_UNIT_LEN] = {
    0x0, 0x0, 0x0, 0x0, 0x65, 0xf8, 0x34, 0x8, 0x9, 0x22, 0x61, 0xbd, 
    0xa5, 0x99, 0x38, 0x9d, 0xf0, 0x33, 0x82, 0xc5, 0xbe, 0x1, 0xa8, 0x1f, 
    0xe0, 0xa, 0x36, 0xf3, 0xf4, 0xbb, 0x65, 0x41, 0x26, 0x3f, 0x80, 0x16, 
    0x27, 0xc4, 0x40, 0xe5, 0x8, 0x9, 0x71, 0x2b, 0xc, 0xac, 0xe7, 0xc2, 
    0x17, 0xe6, 0xe5, 0x5, 0x1a, 0xf8, 0x1d, 0xe9, 0xbf, 0xec, 0x32, 0x4, 
    0xdc, 0xd6, 0x3c, 0x4f, 0x9a, 0x74, 0x10, 0x47
};

/* The NIST CAVP ECDSA sign secret key vector */
static const uint8_t cavp_ecdsa_sign_p521_sk[P521_UNIT_LEN] = {
    0x0, 0x0, 0x0, 0xf7, 0x49, 0xd3, 0x27, 0x4, 0xbc, 0x53, 0x3c, 0xa8, 
    0x2c, 0xef, 0xa, 0xcf, 0x10, 0x3d, 0x8f, 0x4f, 0xba, 0x67, 0xf0, 0x8d, 
    0x26, 0x78, 0xe5, 0x15, 0xed, 0x7d, 0xb8, 0x86, 0x26, 0x7f, 0xfa, 0xf0, 
    0x2f, 0xab, 0x0, 0x80, 0xdc, 0xa2, 0x35, 0x9b, 0x72, 0xf5, 0x74, 0xcc, 
    0xc2, 0x9a, 0xf, 0x21, 0x8c, 0x86, 0x55, 0xc0, 0xcc, 0xcf, 0x9f, 0xee, 
    0x6c, 0x5e, 0x56, 0x7a, 0xa1, 0x4c, 0xb9, 0x26
};

/* The NIST CAVP ECDSA sign random secret nonce k vector */
const uint8_t cavp_ecdsa_sign_p521_k[P521_UNIT_LEN] = {
    0x0, 0x0, 0x0, 0x3a, 0xf5, 0xab, 0x6c, 0xaa, 0x29, 0xa6, 0xde, 0x86, 
    0xa5, 0xba, 0xb9, 0xaa, 0x83, 0xc3, 0xb1, 0x6a, 0x17, 0xff, 0xcd, 0x52, 
    0xb5, 0xc6, 0xc, 0x76, 0x9b, 0xe3, 0x5, 0x3c, 0xdd, 0xde, 0xac, 0x60, 
    0x81, 0x2d, 0x12, 0xfe, 0xcf, 0x46, 0xcf, 0xe1, 0xf3, 0xdb, 0x9a, 0xc9, 
    0xdc, 0xf8, 0x81, 0xfc, 0xec, 0x3f, 0xa, 0xa7, 0x33, 0xd4, 0xec, 0xbb, 
    0x83, 0xc7, 0x59, 0x3e, 0x86, 0x4c, 0x6d, 0xf1
};

/* The NIST CAVP ML-DSA verify test #174 signature R vector */
static const uint8_t cavp_ecdsa_sign_p521_sig_r[P521_UNIT_LEN] =  {
    0x0, 0x0, 0x0, 0x4d, 0xe8, 0x26, 0xea, 0x70, 0x4a, 0xd1, 0xb, 0xc0, 
    0xf7, 0x53, 0x8a, 0xf8, 0xa3, 0x84, 0x3f, 0x28, 0x4f, 0x55, 0xc8, 0xb9, 
    0x46, 0xaf, 0x92, 0x35, 0xaf, 0x5a, 0xf7, 0x4f, 0x2b, 0x76, 0xe0, 0x99, 
    0xe4, 0xbc, 0x72, 0xfd, 0x79, 0xd2, 0x8a, 0x38, 0xf, 0x8d, 0x4b, 0x4c, 
    0x91, 0x9a, 0xc2, 0x90, 0xd2, 0x48, 0xc3, 0x79, 0x83, 0xba, 0x5, 0xae, 
    0xa4, 0x2e, 0x2d, 0xd7, 0x9f, 0xdd, 0x33, 0xe8
};

/* The NIST CAVP ML-DSA verify test #174 signature S vector */
static const uint8_t cavp_ecdsa_sign_p521_sig_s[P521_UNIT_LEN] = {
    0x0, 0x0, 0x0, 0x87, 0x48, 0x8c, 0x85, 0x9a, 0x96, 0xfe, 0xa2, 0x66, 
    0xea, 0x13, 0xbf, 0x6d, 0x11, 0x4c, 0x42, 0x9b, 0x16, 0x3b, 0xe9, 0x7a, 
    0x57, 0x55, 0x90, 0x86, 0xed, 0xb6, 0x4a, 0xed, 0x4a, 0x18, 0x59, 0x4b, 
    0x46, 0xfb, 0x9e, 0xfc, 0x7f, 0xd2, 0x5d, 0x8b, 0x2d, 0xe8, 0xf0, 0x9c, 
    0xa0, 0x58, 0x7f, 0x54, 0xbd, 0x28, 0x72, 0x99, 0xf4, 0x7b, 0x2f, 0xf1, 
    0x24, 0xaa, 0xc5, 0x66, 0xe8, 0xee, 0x3b, 0x43
};

/* SRAM buffers for storing computed signature */
static uint8_t sig_r[P521_UNIT_LEN];
static uint8_t sig_s[P521_UNIT_LEN];

int main(void)
{
    crypto_ec_stat_t stat;
    uint32_t i;

    SYSCFG_DL_init();
 
    /* Run the sign operation */
    stat = Crypto_ECDSA_P521_sign(
        cavp_ecdsa_sign_p521_sk,
        cavp_ecdsa_sign_p521_md,
        cavp_ecdsa_sign_p521_k,
        sig_r,
        sig_s
        );

    /* If the operation was not successful, jump to error trap */
    if (stat != CRYPTO_EC_STAT_ECDSA_SIGN_OK) {
        goto err;
    }

    /* Check generated signature against expected signature */
    for (i=0; i<P521_UNIT_LEN; i++) {
        if ((sig_r[i] != cavp_ecdsa_sign_p521_sig_r[i]) ||\
            (sig_s[i] != cavp_ecdsa_sign_p521_sig_s[i])) {
            goto err;
        }
    }

    /* Trap here on a pass condition */
    while (1) { 
        __NOP(); 
    }

err:
    /* Trap here on an error condition */
    while (1) { 
        __NOP(); 
    }
}
