/* SRAM buffer to store actual computed public key and secret key values */
static uint8_t pk_act[CRYPTO_MLDSA_44_PK_LEN];
static uint8_t sk_act[CRYPTO_MLDSA_44_SK_LEN];

int main(void)
{
    crypto_mldsa_stat_t stat;
    uint32_t i;

    SYSCFG_DL_init();

    /* Compute the keys */
    stat = Crypto_MLDSA_44_keyGen(
        cavp_mldsa_44_keygen_id1_seed, sizeof(cavp_mldsa_44_keygen_id1_seed),
        pk_act, 
        sk_act);

    /* If the operation was not successful, jump to error trap */
    if (stat != CRYPTO_MLDSA_STAT_OK) {
        goto err;
    }

    /* Check generated keys against CAVP expected keys */
    for (i=0; i<CRYPTO_MLDSA_44_PK_LEN; i++) {
        if (pk_act[i] != cavp_mldsa_44_keygen_id1_pk_exp[i]) {
            goto err;
        }
    }
    for (i=0; i<CRYPTO_MLDSA_44_SK_LEN; i++) {
        if (sk_act[i] != cavp_mldsa_44_keygen_id1_sk_exp[i]) {
            goto err;
        }
    }

    /* Trap here on a pass condition */
    while (1) { 
        __NOP(); 
    }

err:
    /* Trap here on an error condition */
    while (1) { 
        __NOP(); 
    }
}
